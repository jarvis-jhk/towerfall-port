#!/usr/bin/env bash
# Build and run a local warpzone-server for tfp-net development and tests.
#
#   scripts/net/dev-server.sh            # foreground, http://127.0.0.1:3012 (udp 3490)
#   scripts/net/dev-server.sh --build    # only build server + wz CLI
#   scripts/net/dev-server.sh --reset    # wipe the dev database first
#   scripts/net/dev-server.sh --check    # only validate packaging/warpzone
#
# Ports: TFP_WZ_PORT (http, default 3012) and TFP_WZ_UDP_PORT (default 3490);
# the warpzone defaults (2998/3478) and the rounds-port ones are used by other
# projects. Point clients at it with WARPZONE_SERVER=http://127.0.0.1:3012.
#
# Everything lives under scratch/net/: the build (wz-target/), the generated
# config and database (wz-dev/). ext/warpzone is only read. The games dir is
# packaging/warpzone, so the server serves our own descriptor.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# From a git worktree: tools, ext/ and the server build live in the main
# checkout; the descriptor served is this tree's packaging/warpzone.
MAIN="${ROOT%%/.claude/worktrees/*}"
[ -f "$MAIN/env.sh" ] || MAIN="$ROOT"
source "$MAIN/env.sh"
WZ="$MAIN/ext/warpzone"
OUT="$MAIN/scratch/net"
DEV="$OUT/wz-dev"
export CARGO_TARGET_DIR="$OUT/wz-target"
# ext/warpzone pins 1.99.1 in rust-toolchain.toml; our stable is that version.
export RUSTUP_TOOLCHAIN=stable
BIN="$CARGO_TARGET_DIR/debug/warpzone-server"
PORT="${TFP_WZ_PORT:-3012}"
UDP_PORT="${TFP_WZ_UDP_PORT:-3490}"

build() {
  (cd "$WZ" && cargo build --locked -q -p warpzone-server -p warpzone-cli)
}

case "${1:-}" in
  --build) build; exit 0 ;;
  --check) [ -x "$BIN" ] || build; exec "$BIN" check-games "$ROOT/packaging/warpzone" ;;
  --reset) rm -rf "$DEV/data" ;;
esac
[ -x "$BIN" ] || build

mkdir -p "$DEV/data"
printf 'moderators = []\nreviewers = []\n' > "$DEV/staff.toml"
cat > "$DEV/server.toml" <<T
# Generated by scripts/net/dev-server.sh — do not edit.
name = "Warpzone (towerfall-port dev)"
public_url = "http://127.0.0.1:$PORT"
http_listen = "127.0.0.1:$PORT"
udp_listen = "127.0.0.1:$UDP_PORT"
data_dir = "data"
games_dir = "$ROOT/packaging/warpzone"
staff_file = "staff.toml"

[limits]
# Test runs register a dozen fresh identities from one IP.
registrations_per_ip_per_day = 100000
logins_per_ip_per_minute = 100000
code_guesses_per_ip_per_minute = 100000
rooms_per_account = 50
T
"$BIN" check-games "$ROOT/packaging/warpzone"
echo "towerfall-port dev server: WARPZONE_SERVER=http://127.0.0.1:$PORT (udp $UDP_PORT)"
cd "$DEV"
exec "$BIN" --config "$DEV/server.toml"
