#!/usr/bin/env python3
"""Regenerates crates/assets/src/audio/sfx_table.rs from the effect catalogue
in docs/spec/audio.md (section 10). Run: python3 -I scripts/dev/gen-sfx-table.py"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parents[2]
spec = (root / "docs/spec/audio.md").read_text().splitlines()
start = next(i for i, l in enumerate(spec) if l.startswith("## 10."))
rows, dark = [], False
for line in spec[start:]:
    if line.startswith("#### "):
        dark = "Dark World" in line
        continue
    m = re.match(r"^\| ([a-z][A-Za-z0-9_]*(?:\[\])?) \| ([A-Z0-9_]+) \| ([^|]+) \|$", line.strip())
    if not m:
        continue
    field, base, kind = m.group(1), m.group(2), m.group(3).strip()
    pitch = not kind.endswith("*")
    kind = kind.rstrip("*")
    if kind == "1":
        k, files = "SfxKind::Plain", base
    elif kind == "L":
        k, files = "SfxKind::Looped", base
    elif kind.startswith("I"):
        k, files = f"SfxKind::Instanced({int(kind[1:])})", base
    elif kind.startswith("V"):
        assert base.endswith("_NN"), base
        k, files = f"SfxKind::Varied({int(kind[1:])})", base[:-3]
    elif kind.startswith("1x"):
        assert base.endswith("_0N"), base
        k, files = f"SfxKind::Array({int(kind[2:])})", base[:-3]
    else:
        sys.exit(f"unknown kind {kind} for {field}")
    rows.append((field.rstrip("[]"), files, k, pitch, dark))

out = ["// @generated by scripts/dev/gen-sfx-table.py from docs/spec/audio.md §10 — do not edit.",
       "use super::catalogue::{SfxDef, SfxKind};", "",
       "pub static SFX_TABLE: &[SfxDef] = &["]
for name, files, k, pitch, dark in rows:
    out.append(f'    SfxDef {{ name: "{name}", file: "{files}", kind: {k}, obeys_pitch: {str(pitch).lower()}, dark_world: {str(dark).lower()} }},')
out.append("];")
(root / "crates/assets/src/audio/sfx_table.rs").write_text("\n".join(out) + "\n")
print(f"{len(rows)} effects")
